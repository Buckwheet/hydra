/// A ZIP holding `members`, written by `zip`'s own writer.
///
/// `zip64` forces the per-entry ZIP64 form (`SimpleFileOptions::large_file`):
/// the 32-bit size fields become 0xFFFFFFFF and the real values move into the
/// 0x0001 extra field, which the hand-written reader had to parse itself.
pub fn archive_with(
    members: &[(&str, &[u8])],
    method: zip::CompressionMethod,
    zip64: bool,
) -> Vec<u8> {
    write_archive(members, method, zip64, false)
}

/// A ZIP with a real ZIP64 **end of central directory** section (the
/// `PK\x06\x06` record and its `PK\x06\x07` locator), which `zip`'s writer
/// emits when the archive is large or when it is asked for an extensible data
/// sector.
pub fn archive_zip64_section(members: &[(&str, &[u8])], method: zip::CompressionMethod) -> Vec<u8> {
    write_archive(members, method, false, true)
}

fn write_archive(
    members: &[(&str, &[u8])],
    method: zip::CompressionMethod,
    zip64_entry: bool,
    zip64_end: bool,
) -> Vec<u8> {
    let mut writer = zip::ZipWriter::new(Cursor::new(Vec::new()));
    if zip64_end {
        writer.set_raw_zip64_extensible_data_sector(Vec::new().into_boxed_slice());
    }
    for (name, bytes) in members {
        let options = zip::write::SimpleFileOptions::default()
            .compression_method(method)
            .large_file(zip64_entry);
        writer.start_file(*name, options).expect("starts a member");
        writer.write_all(bytes).expect("writes a member");
    }
    writer.finish().expect("finishes").into_inner()
}

/// Where the 4-byte signature `magic` first occurs.
pub fn find(bytes: &[u8], magic: [u8; 4]) -> Option<usize> {
    bytes.windows(4).position(|window| window == magic)
}
